"""Runs a question set against every prompting strategy; writes results/*.json and EXAMPLES.md"""
import json
import sqlite3
from pathlib import Path

import db_bot

QUESTIONS = [
    "How many active memberships are there for each membership type?",
    "Which membership type has generated the most completed payment revenue?",
    "List the Family memberships and how many members each one covers.",
    "Which facilities can Student members access and at what access level?",
    "Who has the most reservations, and how many?",
    "How many reservations were cancelled for each facility?",
    "Which memberships have a failed payment?",
    "Which members have reserved a facility their membership type has no access to?",
    "Which family memberships have more members than their plan allows?",
    "What was the total refunded amount last month?",
]

db_bot.build_db()
Path("results").mkdir(exist_ok=True)
all_results, total = [], 0.0
for strat in db_bot.STRATEGIES:
    for q in QUESTIONS:
        r = db_bot.ask(q, strat)
        total += r["cost_usd"]
        all_results.append(r)
        print(strat, "|", q, "|", "ERROR" if r["error"] else f'{len(r["rows"])} rows')
json.dump(all_results, open("results/experiments.json", "w"), indent=2, default=str)

lines = ["# Experiment results (auto-generated by `run_experiments.py`)\n",
         f"Model: `{db_bot.MODEL}` - total cost for all runs: ~${total:.4f}\n",
         "| Strategy | Succeeded (no error) | Avg. SQL tokens in |", "|---|---|---|"]
for s in db_bot.STRATEGIES:
    rs = [r for r in all_results if r["strategy"] == s]
    lines.append(f"| {s} | {sum(1 for r in rs if not r['error'])}/{len(rs)} | "
                 f"{sum(r['tokens']['input'] for r in rs) // len(rs)} |")
lines.append("")
for q in QUESTIONS:
    lines.append(f"## {q}\n")
    for r in [x for x in all_results if x["question"] == q]:
        lines.append(f"**{r['strategy']}**\n")
        lines.append(f"```sql\n{r['sql']}\n```")
        if r["error"]:
            lines.append(f"Error: `{r['error']}`\n")
        else:
            lines.append(f"Rows returned: {len(r['rows'])} - first rows: `{r['rows'][:4]}`\n")
            lines.append(f"> {r['answer']}\n")
Path("EXAMPLES.md").write_text("\n".join(lines), encoding="utf-8")
print(f"done, ~${total:.4f}")
